// Seed the SokaSoko official house account. Idempotent — safe to re-run.
//
// Usage:
//   node scripts/seed-sokasoko-account.js
//
// Requires MONGO_URL in .env (falls back to a local Mongo if unset).
//
// The house account is a regular User row with isHouseAccount=true.
// Its login credentials are irrelevant (an admin never logs in AS the
// house account — they log in as themselves with isAdmin=true, then
// reply-as-SokaSoko via the admin endpoint). Password is a random
// 32-byte hex string so no one can guess it.

require('dotenv').config();
const crypto = require('crypto');
const mongoose = require('mongoose');
// User has ref: 'Academy' via linkedAcademy — Mongoose refuses to
// resolve refs unless the target model is registered, even if we
// never actually populate() it. Requiring the model here forces
// registration.
require('../src/Academy/academy.model');
const User = require('../src/User/user.model');

const MONGO_URL = process.env.MONGO_URL
  || process.env.MONGODB_URI
  || 'mongodb://localhost:27017/sokasoko';

// Note: the User schema uses snake_case for org/sponsor fields
// (sponsor_type, entity_name, company_name) even though most other
// fields are camelCase. Using camelCase for these on User.create()
// silently drops them — hence explicit snake_case below. There is
// NO is_verified field on the User schema; the auth flow doesn't
// gate on verification for this beta.
async function main() {
  await mongoose.connect(MONGO_URL);
  const existing = await User.findOne({ isHouseAccount: true });
  const houseFields = {
    firstName: 'SokaSoko',
    lastName: 'Msaidizi',
    company_name: 'SokaSoko',
    entity_name: 'SokaSoko',
    sponsor_type: 'Entity',
    type: 'SPONSOR',
    // Phone must be unique + 10 digits per the User schema. Synthetic
    // in-band-known number: no real user can register with this because
    // the seed grabs it first.
    phone: '0700000001',
    // Explicit accountNumber — the normal one is generated by the
    // user.http.router create endpoint, which we bypass here. Hard-
    // coded SS suffix marks this as the official SokaSoko account so
    // it's visually distinct from any real SPONSOR row.
    accountNumber: 'TFH-SS-A000001',
    isHouseAccount: true,
    // Bypass the beta testing gate so support is reachable during beta.
    betaTester: true,
  };
  if (existing) {
    // Patch missing/stale fields — safe to re-run.
    Object.assign(existing, houseFields);
    if (!existing.password) {
      existing.password = crypto.randomBytes(32).toString('hex');
    }
    await existing.save();
    console.log('✓ SokaSoko house account patched');
    console.log('  id:', existing._id.toString());
    console.log('  accountNumber:', existing.accountNumber);
    console.log('  company_name:', existing.company_name);
    await mongoose.disconnect();
    process.exit(0);
  }

  const account = await User.create({
    ...houseFields,
    password: crypto.randomBytes(32).toString('hex'),
  });

  console.log('✓ Created SokaSoko house account');
  console.log('  id:', account._id.toString());
  console.log('  accountNumber:', account.accountNumber);
  console.log('  company_name:', account.company_name);
  console.log('');
  console.log('Next: grant yourself admin access with:');
  console.log('  node scripts/grant-admin.js <your-phone>');

  await mongoose.disconnect();
  process.exit(0);
}

main().catch((err) => {
  console.error('✗ Failed:', err.message);
  process.exit(1);
});
